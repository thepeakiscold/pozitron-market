class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('pozitron_lang') || 'tr';
  }

  setLanguage(lang) {
    if (lang !== 'tr' && lang !== 'en') lang = 'tr';
    this.currentLang = lang;
    localStorage.setItem('pozitron_lang', lang);
    document.documentElement.lang = lang;
    this.updateDom();
  }

  t(key, params = {}) {
    const langDict = i18nData[this.currentLang] || i18nData['tr'];
    let text = langDict[key] || (i18nData['en'] && i18nData['en'][key]) || key;
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), pVal);
    }
    return text;
  }

  updateDom() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val.includes('<')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = this.t(key);
    });

    // Update Flag & Label
    const flagEl = document.getElementById('lang-flag');
    const labelEl = document.getElementById('lang-label');
    if (flagEl && labelEl) {
      if (this.currentLang === 'tr') {
        flagEl.textContent = '🇹🇷';
        labelEl.textContent = 'TR';
      } else {
        flagEl.textContent = '🇬🇧';
        labelEl.textContent = 'EN';
      }
    }

    // Trigger event for components
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: this.currentLang } }));
  }
}

window.i18n = new I18nManager();
